# +  : Addition (adds two numbers or concatenates strings)
# *  : Multiplication (multiplies two numbers or repeats sequences)
# ** : Exponentiation (raises left operand to the power of right operand)
# /  : Division (divides left operand by right, always returns float)
# // : Floor division (divides and rounds down to nearest integer)
# %  : Modulus (returns the remainder of division)
# >  : Greater than (returns True if left value is greater than right)
# <= : Less than or equal to (returns True if left value is <= right)

print("5 + 2 =", 5 + 2)
print("5 * 2 =", 5 * 2)
print("5 ** 2 =", 5 ** 2)
print("5 / 2 =", 5 / 2)
print("5 // 2 =", 5 // 2)
print("5 % 2 =", 5 % 2)
print("5 > 2 =", 5 > 2)
print("5 <= 2 =", 5 <= 2)
